using Microsoft.Extensions.Diagnostics.HealthChecks;
using Orders.Infrastructure.Persistence;

namespace Orders.Api.HealthChecks;

public sealed class OrdersDatabaseHealthCheck(OrdersDbContext dbContext) : IHealthCheck
{
    public async Task<HealthCheckResult> CheckHealthAsync(
        HealthCheckContext context,
        CancellationToken cancellationToken = default)
    {
        try
        {
            return await dbContext.Database.CanConnectAsync(cancellationToken)
                ? HealthCheckResult.Healthy()
                : HealthCheckResult.Unhealthy("Orders database is unavailable.");
        }
        catch (OperationCanceledException) when (cancellationToken.IsCancellationRequested)
        {
            throw;
        }
        catch (Exception)
        {
            return HealthCheckResult.Unhealthy("Orders database is unavailable.");
        }
    }
}
